/* ---------- Generate Quote ---------- */

var button = document.getElementById("generateQuote");

if (button) {

    button.onclick = function() {

        var language =
            document.getElementById("language").value;

        var category =
            document.getElementById("category").value;

        var foundQuotes = [];

        for (var i = 0; i < quotes.length; i++) {

            if (quotes[i].language == language &&
                quotes[i].category == category) {

                foundQuotes.push(quotes[i]);

            }

        }


        if (foundQuotes.length > 0) {

            var currentQuote =
                foundQuotes[quoteIndex];


            quoteIndex++;


            if (quoteIndex >= foundQuotes.length) {

                quoteIndex = 0;

            }


            document.getElementById("generatedQuote").innerHTML =
                "“" + currentQuote.quote + "”";


            document.getElementById("generatedAuthor").innerHTML =
                "— " + currentQuote.author;
     
              document.getElementById("favorite").innerHTML =
             "♡ Favorite";
          


            var quoteContent =
                document.querySelector(".quote-content");


            if (currentQuote.image) {

                document.getElementById("generatedImage").src =
                    currentQuote.image;

                document.getElementById("generatedImage").style.display =
                    "block";

                quoteContent.classList.remove("no-image");

            }

            else {

                document.getElementById("generatedImage").style.display =
                    "none";

                quoteContent.classList.add("no-image");

            }

        }

        else {

            document.getElementById("generatedQuote").innerHTML =
                "Please select a language and category.";

            document.getElementById("generatedAuthor").innerHTML =
                "";

            document.getElementById("generatedImage").style.display =
                "none";

            document.querySelector(".quote-content")
                .classList.add("no-image");

        }

    };

}


/* ---------- Favorite ---------- */

var favoriteButton =
    document.getElementById("favorite");


if (favoriteButton) {

    favoriteButton.onclick = function() {

        var quote =
            document.getElementById("generatedQuote").innerText;

        var author =
            document.getElementById("generatedAuthor").innerText;


        var favorites =
            JSON.parse(localStorage.getItem("favorites")) || [];


        var alreadyFavorite = false;


        for (var i = 0; i < favorites.length; i++) {

            if (favorites[i].quote == quote) {

                alreadyFavorite = true;

            }

        }


        if (!alreadyFavorite) {

            favorites.push({
                quote: quote,
                author: author
            });


            localStorage.setItem(
                "favorites",
                JSON.stringify(favorites)
            );


            favoriteButton.innerHTML =
                "❤️ Added to Favorites";

        }

        else {

            favoriteButton.innerHTML =
                "❤️ Already in Favorites";

        }

    };

}


/* ---------- Copy Quote ---------- */

var copyButton =
    document.getElementById("copy");


if (copyButton) {

    copyButton.onclick = function() {

        var quote =
            document.getElementById("generatedQuote").innerText;

        var author =
            document.getElementById("generatedAuthor").innerText;


        var textToCopy =
            quote + "\n" + author;


        navigator.clipboard.writeText(textToCopy);


        copyButton.innerHTML =
            "✅ Copied!";


        setTimeout(function() {

            copyButton.innerHTML =
                "📋 Copy Quote";

        }, 1500);

    };

}


/* ---------- Display Favorites ---------- */

var favoriteContainer =
    document.getElementById("favoriteQuotes");


if (favoriteContainer) {

    var favorites =
        JSON.parse(localStorage.getItem("favorites")) || [];


    if (favorites.length == 0) {

        favoriteContainer.innerHTML =
            "<p>No favorite quotes yet.</p>";

    }

    else {

        for (var i = 0; i < favorites.length; i++) {

            var favorite =
                favorites[i];


            var favoriteCard =
                document.createElement("div");


            favoriteCard.className =
                "favorite-card";


            favoriteCard.innerHTML =
                "<p>“" + favorite.quote + "”</p>" +
                "<p>" + favorite.author + "</p>" +
                "<button onclick=\"removeFavorite(" + i + ")\">Remove</button>";


            favoriteContainer.appendChild(
                favoriteCard
            );

        }

    }

}


/* ---------- Remove Favorite ---------- */

function removeFavorite(index) {

    var favorites =
        JSON.parse(localStorage.getItem("favorites")) || [];


    favorites.splice(index, 1);


    localStorage.setItem(
        "favorites",
        JSON.stringify(favorites)
    );


    location.reload();

}